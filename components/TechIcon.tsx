export function TechIcon({ name, className = "size-4" }: { name: string; className?: string }) {
  const entry = getTechIcon(name);
  const Icon = entry.Icon;

  return <Icon className={className} style={{ color: entry.color }} aria-hidden />;
}

export function getTechIcon(name: string) {
  return icons[name] ?? fallbackIcons.find(({ keywords }) =>
    keywords.some((keyword) => name.toLowerCase().includes(keyword)),
  ) ?? { Icon: FaCode, color: "#a1a1aa" };
}

